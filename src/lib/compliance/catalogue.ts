export type Requirement = {
  /** Stable key (also stored on the company's checklist row). Never rename; add a new one instead. */
  code: string;
  category: ComplianceCategory;
  kind: RequirementKind;
  name: string;
  /** Who issues it or receives the filing. */
  authority: string;
  /** "always": every company like ours; "conditional": only when `condition` is true. */
  appliesTo: "always" | "conditional";
  condition?: string;
  /** What it is for, in plain words. */
  purpose: string;
  /** Typical papers needed to apply or to show on inspection. */
  documentsNeeded: string[];
  /** Typical renewal (wording, not a promise). */
  renewal: string;
  /** When it is due, in words. */
  dueRule: string;
  /**
   * Calendar rule for recurring filings, used to build the tax & filing calendar:
   * the period is a month, a quarter or the financial year (quarters and years end on the
   * company's year-end month); due on `dueDay` (31 = last day of the month) of the month
   * `dueOffsetMonths` after the period's last month (0 = in that month, negative = before it).
   * No `dueDay`: not put on the calendar automatically (the company sets a due date itself).
   */
  frequency: Frequency;
  dueDay?: number;
  dueOffsetMonths?: number;
  /** What can go wrong (summary, not the legal penalty). */
  penalty: string;
  /** Official website, only where we are confident it is correct. */
  website?: string;
  /** True when a deadline, threshold, rate, fee or rule must be confirmed with the authority. */
  verify: boolean;
  verifyNote?: string;
  /** Added by default for a newly registered general supply company (BRELA done, no supply licences yet). */
  starter: boolean;
  /** Finance (not only management) may update it: tax and social-security items. */
  finance: boolean;
  tags: ActivityTag[];
  /** Extra words for searching (Kiswahili names, abbreviations). */
  keywords?: string[];
  sort: number;
};

