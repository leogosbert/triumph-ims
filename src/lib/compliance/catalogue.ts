/**
 * registration: done once (may need updating on changes).
 * licence:      has an issue and expiry date; belongs in the Licences register.
 * filing:       a return or payment that comes back (monthly, quarterly, yearly or on change).
 * record:       something to keep up to date and show on request (registers, contracts, policies).
 */
export type RequirementKind = "registration" | "licence" | "filing" | "record";

/** How often a filing comes back. "none": one-off, on change, or a date the company sets itself. */
export type Frequency = "none" | "monthly" | "quarterly" | "annual";

