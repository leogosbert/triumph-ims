/**
 * A small QR code encoder (byte mode, versions 1-40, error correction level M by default), so the
 * TRA verification link and the pay link can be printed on invoices without a new package.
 * Follows ISO/IEC 18004 the same way Project Nayuki's MIT-licensed reference does.
 * Pure function, no network; tested in scripts/test-money.ts (decoded back with jsQR).
 */

export type QrLevel = "L" | "M" | "Q" | "H";

const LEVEL_INDEX: Record<QrLevel, number> = { L: 0, M: 1, Q: 2, H: 3 };
const FORMAT_BITS: Record<QrLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };

// prettier-ignore
